#!/usr/bin/env python3
"""Mechanically replace the non-ASCII code points found in FUSE's tracked
source files (2026-10-15 ASCII-only ruling) with a meaning-preserving ASCII
spelling, the same substitution everywhere a given code point plays the same
role.

Scope: every file `tools/check-ascii.py` would scan (tracked, not under
upstream/, not *.md, not a declared binary fixture) MINUS test/golden/*.ir --
those IR dumps are test/ir/golden_ir_test.cpp's byte-exact comparison target
and are regenerated by running that suite with FUSE_UPDATE_GOLDEN=1 after the
one source change that puts a non-ASCII character into their text
(include/fuse/base/units.hpp's unit-string separator), not hand-edited here.

Code points handled, and why each ASCII spelling was chosen (see the owner's
track report for the per-file counts this produced):
  U+00A7 SECTION SIGN          -> "Section " (with any run of spaces/tabs
                                   already following the sign collapsed to
                                   the one space after "Section", so
                                   "Section  5" never results)
  U+2014 EM DASH                -> "--" (every occurrence in this tree already
                                   has a literal space on each side, so the
                                   character substitution alone reproduces
                                   the prose dash)
  U+2026 HORIZONTAL ELLIPSIS     -> "..."
  U+2218 RING OPERATOR           -> " o " (function composition, the only use
                                   found: `kind_a + "o" + kind_b` and the
                                   matching prose "A o B")
  U+2248 ALMOST EQUAL TO         -> "~="

U+00B7 MIDDLE DOT is NOT handled by the general substitution above: it is used
for two unrelated purposes in this tree (an SI-unit multiplication separator,
and a placeholder dot in "apply(x, ...)"-style math prose marking an omitted
argument), and the two need different ASCII spellings. Those occurrences are
listed explicitly in MIDDLE_DOT_FIXES below, one literal old/new pair per
call site, so each is reviewed on its own rather than guessed from a regex.

Keep this script: re-run it (it is idempotent -- a clean file is a no-op) if
a new non-ASCII character ever lands in a tracked file again.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import importlib.util

_here = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("check_ascii", _here / "check-ascii.py")
check_ascii = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check_ascii)

SECTION_SIGN = re.compile("\u00a7[ \t]*")
EM_DASH = "\u2014"
ELLIPSIS = "\u2026"
RING_OP = "\u2218"
ALMOST_EQ = "\u2248"

# Files whose IR-dump golden text is regenerated by the test suite, not fixed
# here (see module docstring).
REGENERATED_GOLDENS = {
    "test/golden/pair_accumulate_remap_relax.ir",
    "test/golden/pair_explicit.ir",
    "test/golden/pair_iterated.ir",
    "test/golden/pair_lowfive_bound.ir",
}

# U+00B7 MIDDLE DOT: one literal (old, new) pair per call site, applied with
# str.replace (each old string is unique in its file; the script asserts that
# below rather than assuming it).
MIDDLE_DOT_FIXES: dict[str, list[tuple[str, str]]] = {
    "include/fuse/base/units.hpp": [
        ('if (!out.empty()) out += "\u00b7";  // middle dot',
         'if (!out.empty()) out += "*";  // multiplication separator between SI base units'),
        ("cannot assign kg\u00b7m^-1\u00b7s^-2 to kg\u00b7m^-1\u00b7s^-2",
         "cannot assign kg*m^-1*s^-2 to kg*m^-1*s^-2"),
        ('if (scale != Rational{1}) out = scale.to_string() + "\u00b7" + out;',
         'if (scale != Rational{1}) out = scale.to_string() + "*" + out;'),
    ],
    "test/base/units_test.cpp": [
        ("// W = kg\u00b7m^2\u00b7s^-3", "// W = kg*m^2*s^-3"),
    ],
    "include/fuse/backend/linear_operator.hpp": [
        ("/// ||A^T y \u00b7 x - y \u00b7 A x|| relative to the magnitudes involved, for one pair of",
         "/// ||A^T y * x - y * A x|| relative to the magnitudes involved, for one pair of"),
    ],
    "include/fuse/linalg/pcg.hpp": [
        ("/// FRESH `apply(x, \u00b7)` first, and only the relative norm of THAT",
         "/// FRESH `apply(x, _)` first, and only the relative norm of THAT"),
    ],
}


def fix_text(text: str) -> str:
    text = SECTION_SIGN.sub("Section ", text)
    text = text.replace(EM_DASH, "--")
    text = text.replace(ELLIPSIS, "...")
    text = text.replace(RING_OP, " o ")
    text = text.replace(ALMOST_EQ, "~=")
    return text


def apply_middle_dot_fixes(rel_posix: str, text: str) -> str:
    for old, new in MIDDLE_DOT_FIXES.get(rel_posix, []):
        count = text.count(old)
        if count != 1:
            raise SystemExit(
                f"ascii-fix: {rel_posix}: expected exactly one occurrence of "
                f"{old!r}, found {count}")
        text = text.replace(old, new)
    return text


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    if len(argv) > 1:
        files = [Path(a).resolve() for a in argv[1:]]
    else:
        files = check_ascii.tracked_files(root)
    changed = 0
    counts: dict[str, int] = {}
    for path in sorted(files):
        if not path.is_file():
            continue
        rel_posix = path.relative_to(root).as_posix()
        if check_ascii.excluded(rel_posix):
            continue
        if check_ascii.is_declared_binary_fixture(rel_posix):
            continue
        if rel_posix in REGENERATED_GOLDENS:
            continue
        data = path.read_bytes()
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            continue
        if all(ord(c) <= 0x7F for c in text):
            continue
        before = text
        for ch in before:
            if ord(ch) > 0x7F:
                counts[ch] = counts.get(ch, 0) + 1
        fixed = fix_text(before)
        fixed = apply_middle_dot_fixes(rel_posix, fixed)
        if fixed != before:
            path.write_bytes(fixed.encode("utf-8"))
            changed += 1
            print(f"fixed: {rel_posix}")
    print(f"ascii-fix: {changed} file(s) changed")
    for ch, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        import unicodedata
        print(f"  U+{ord(ch):04X} {unicodedata.name(ch, '?')}: {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
